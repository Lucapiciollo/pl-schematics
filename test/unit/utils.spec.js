const { Tree } = require('@angular-devkit/schematics');
const { parseJsonc, readJsonFile, overwriteJsonFile } = require('../../src/pl-schematics/utils/json.utils');
const { validateNamePackage, getLibBaseName } = require('../../src/pl-schematics/rules/normalize-options.rule');
const { addLibraryTsConfigPath, addLibraryProjectToWorkspace } = require('../../src/pl-schematics/utils/library.utils');
const { detectApp, resolveArchitecture, buildDefaultPath } = require('../../src/pl-schematics/utils/workspace.utils');
const { addImports, addToArrayProperty } = require('../../src/pl-schematics/utils/ts-edit.utils');
const { getAngularMajorVersion, getVersions } = require('../../src/pl-schematics/utils/versions.utils');
const { TSCONFIG, createWorkspace } = require('./helpers');

const logger = { logger: { info() {}, warn() {} } };

describe('json.utils (JSONC)', () => {
  it('parses the tsconfig.json generated by ng new (comments, trailing comma)', () => {
    const json = parseJsonc(TSCONFIG, 'tsconfig.json');
    expect(json.compilerOptions.strict).toBe(true);
    expect(json.compilerOptions.target).toBe('ES2022');
  });

  it('throws a clear error on really malformed JSON', () => {
    expect(() => parseJsonc('{ "a": ', 'broken.json')).toThrowError(/Invalid JSON in "broken.json"/);
  });

  it('overwriteJsonFile keeps comments and untouched keys', () => {
    const tree = Tree.empty();
    tree.create('tsconfig.json', TSCONFIG);
    const json = readJsonFile(tree, 'tsconfig.json');
    json.compilerOptions.paths = { lib: ['./projects/lib/src/public-api.ts'] };
    overwriteJsonFile(tree, 'tsconfig.json', json);
    const out = tree.read('tsconfig.json').toString();
    expect(out).toContain('/* To learn more about Typescript configuration file');
    expect(out).toContain('// commento di riga');
    expect(out).toContain('"compileOnSave": false');
    expect(readJsonFile(tree, 'tsconfig.json').compilerOptions.paths.lib[0]).toBe('./projects/lib/src/public-api.ts');
  });
});

describe('namePackage', () => {
  it('accepts single and multi-segment names', () => {
    expect(validateNamePackage('my-app')).toBe('my-app');
    expect(validateNamePackage('cloud/agic')).toBe('cloud/agic');
    expect(validateNamePackage('My_App/sub-1')).toBe('My_App/sub-1');
  });

  it('rejects empty segments, dot segments, spaces and missing values', () => {
    ['a//b', '/a', 'a/', '../x', 'a/./b', 'a b', 'a\\b', '', undefined].forEach((value) => {
      expect(() => validateNamePackage(value)).toThrowError(/namePackage/);
    });
  });

  it('derives sanitized kebab-case library names (segments joined with "-")', () => {
    expect(getLibBaseName('cloud/agic')).toBe('cloud-agic');
    expect(getLibBaseName('My_App')).toBe('my-app');
    expect(getLibBaseName('my-app')).toBe('my-app');
  });
});

describe('library path mapping and registration', () => {
  it('writes a relative "./projects/..." mapping (no baseUrl needed, avoids TS5090)', () => {
    const tree = createWorkspace({ major: 19, standalone: true });
    addLibraryTsConfigPath(tree, logger, 'my-lib');
    const paths = readJsonFile(tree, 'tsconfig.json').compilerOptions.paths;
    expect(paths['my-lib']).toEqual(['./projects/my-lib/src/public-api.ts']);
  });

  it('uses the ng-packagr builder of the workspace (Angular 19 vs 20+)', () => {
    const t19 = createWorkspace({ major: 19, standalone: true });
    addLibraryProjectToWorkspace(t19, logger, 'x-shared', 'app');
    expect(readJsonFile(t19, 'angular.json').projects['x-shared'].architect.build.builder).toBe('@angular-devkit/build-angular:ng-packagr');

    const t20 = createWorkspace({ major: 20, standalone: true });
    addLibraryProjectToWorkspace(t20, logger, 'x-shared', 'app');
    expect(readJsonFile(t20, 'angular.json').projects['x-shared'].architect.build.builder).toBe('@angular/build:ng-packagr');
  });
});

describe('application detection', () => {
  it('detects a standalone Angular 19 app (app.component.ts)', () => {
    const app = detectApp(createWorkspace({ major: 19, standalone: true }), {});
    expect(app.architecture).toBe('standalone');
    expect(app.rootComponent.file).toBe('src/app/app.component.ts');
    expect(app.rootComponent.className).toBe('AppComponent');
    expect(app.rootComponent.templateFile).toBe('src/app/app.component.html');
    expect(app.configFile).toBe('src/app/app.config.ts');
  });

  it('detects a classic Angular 20 app (app-module.ts, app.ts)', () => {
    const app = detectApp(createWorkspace({ major: 20, standalone: false }), {});
    expect(app.architecture).toBe('classic');
    expect(app.moduleFile).toBe('src/app/app-module.ts');
    expect(app.routingModuleFile).toBe('src/app/app-routing-module.ts');
    expect(app.dashNaming).toBe(true);
    expect(app.rootComponent.file).toBe('src/app/app.ts');
    expect(app.rootComponent.className).toBe('App');
  });

  it('detects a classic Angular 19 app (app.module.ts)', () => {
    const app = detectApp(createWorkspace({ major: 19, standalone: false }), {});
    expect(app.architecture).toBe('classic');
    expect(app.moduleFile).toBe('src/app/app.module.ts');
    expect(app.dashNaming).toBe(false);
  });

  it('fails clearly when main.ts has neither bootstrapApplication nor bootstrapModule', () => {
    const tree = createWorkspace({ major: 19, standalone: true });
    tree.overwrite('src/main.ts', 'console.log("hi");');
    expect(() => detectApp(tree, {})).toThrowError(/Cannot detect the application architecture/);
  });

  it('resolveArchitecture: auto follows the detection, mismatches throw', () => {
    expect(resolveArchitecture('auto', 'standalone')).toBe('standalone');
    expect(resolveArchitecture(undefined, 'classic')).toBe('classic');
    expect(resolveArchitecture('classic', 'classic')).toBe('classic');
    expect(() => resolveArchitecture('classic', 'standalone')).toThrowError(/Requested --architecture=classic/);
  });

  it('buildDefaultPath mimics the Angular utility', () => {
    expect(buildDefaultPath({ projectType: 'application', sourceRoot: 'src' })).toBe('src/app');
    expect(buildDefaultPath({ projectType: 'application', root: 'projects/x' })).toBe('projects/x/src/app');
    expect(buildDefaultPath({ projectType: 'library', sourceRoot: 'projects/l/src' })).toBe('projects/l/src/lib');
  });
});

describe('versions', () => {
  it('reads the Angular major and rejects unsupported/undeterminable versions (no "latest" fallback)', () => {
    expect(getAngularMajorVersion(createWorkspace({ major: 21, standalone: true }))).toBe(21);
    const old = createWorkspace({ major: 19, standalone: true });
    old.overwrite('package.json', JSON.stringify({ dependencies: { '@angular/core': '^18.2.0' } }));
    expect(() => getAngularMajorVersion(old)).toThrowError(/Angular 18 is not supported/);
    const latest = createWorkspace({ major: 19, standalone: true });
    latest.overwrite('package.json', JSON.stringify({ dependencies: { '@angular/core': 'latest' } }));
    expect(() => getAngularMajorVersion(latest)).toThrowError(/Cannot determine the Angular version/);
  });

  it('returns "latest" only for the internal libraries (pl-core-utils-library, pl-decorator, pl-loading-trace)', () => {
    const internal = ['plCoreUtilsLibrary', 'plDecorator', 'plLoadingTrace'];
    [19, 20, 21].forEach((major) => {
      const versions = getVersions(major);
      Object.keys(versions).forEach((key) => {
        if (internal.indexOf(key) >= 0) {
          expect(versions[key]).toBe('latest');
        } else {
          expect(String(versions[key])).not.toMatch(/latest/);
        }
      });
    });
  });
});

describe('ts-edit.utils', () => {
  it('addImports merges into an existing import and is idempotent', () => {
    let out = addImports("import { A } from 'x';\nconst a = 1;\n", { symbols: ['A', 'B'], from: 'x' });
    expect(out).toContain("import { A, B } from 'x';");
    expect(addImports(out, { symbols: ['B'], from: 'x' })).toBe(out);
    out = addImports("import { A } from 'x';\n", { symbols: ['C'], from: 'y' });
    expect(out).toContain("import { C } from 'y';");
  });

  it('addToArrayProperty appends to an existing array and creates a missing one', () => {
    const content = '@NgModule({\n  imports: [BrowserModule, Foo(1, [2])],\n})\nexport class M {}\n';
    const out = addToArrayProperty(content, { property: 'imports', anchor: /@NgModule\(\{/, items: [{ key: 'Bar', code: 'Bar' }, { key: 'Foo', code: 'Foo' }] });
    expect(out).toContain('Foo(1, [2]),\n    Bar');
    expect((out.match(/Foo/g) || []).length).toBe(1);

    const created = addToArrayProperty('@NgModule({\n})\nexport class M {}\n', { property: 'providers', anchor: /@NgModule\(\{/, items: [{ key: 'P', code: 'P' }] });
    expect(created).toContain('providers: [');
  });
});
